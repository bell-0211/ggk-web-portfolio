  var currentLang = localStorage.getItem('ggk_lang');
  if (currentLang !== 'zh' && currentLang !== 'en') currentLang = 'zh';

  function applyLang(lang) {
    if (lang !== 'zh' && lang !== 'en') lang = 'zh';   // 脏值容错：非法值强制回退 zh
    currentLang = lang;
    localStorage.setItem('ggk_lang', lang);
    var dict = GGK_I18N[lang] || GGK_I18N.zh;          // dict 为空时回退 zh 字典，保证切换永远有响应

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = dict[key];
        } else {
          /* 打字机标题特殊处理：标记全文，不直接覆盖（避免破坏光标/打字过程） */
          if (el.hasAttribute('data-typewriter')) {
            el.setAttribute('data-typewriter-text', dict[key]);
          } else {
            el.textContent = dict[key];
          }
        }
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

    var toggle = document.querySelector('.lang-toggle');
    if (toggle) {
      var spans = toggle.querySelectorAll('span');
      spans.forEach(function (s) {
        if ((lang === 'zh' && s.textContent === '中文') || (lang === 'en' && s.textContent === 'EN')) {
          s.className = 'active';
        } else {
          s.className = 'inactive';
        }
      });
    }

    /* 通知其他模块语言已切换（如打字机动画需感知） */
    document.dispatchEvent(new CustomEvent('ggk:langChanged', { detail: { lang: lang } }));
  }

  function ggkToggleLang() {
    var newLang = currentLang === 'zh' ? 'en' : 'zh';
    applyLang(newLang);
  }

  window.GGK_I18N = GGK_I18N;
  window.ggkApplyLang = applyLang;
  window.ggkToggleLang = ggkToggleLang;

  // 用事件监听接管 .lang-toggle 点击，替代内联 onclick，绑定更稳健
  function bindLangToggle() {
    var toggle = document.querySelector('.lang-toggle');
    if (!toggle || toggle.getAttribute('data-lang-bound')) return;
    toggle.setAttribute('data-lang-bound', '1');
    toggle.addEventListener('click', function (e) {
      e.preventDefault();
      ggkToggleLang();
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () { bindLangToggle(); applyLang(currentLang); });
  } else {
    bindLangToggle();
    applyLang(currentLang);
  }
